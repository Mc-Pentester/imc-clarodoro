import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const pagePath = 'private-pages/whatsapp-send.php';
const page = fs.readFileSync(pagePath, 'utf8');
const scripts = [...page.matchAll(/<script>([\s\S]*?)<\/script>/gi)];
assert.equal(scripts.length, 1, 'Expected exactly one inline script');
const script = scripts[0][1];
new vm.Script(script, { filename: pagePath });

const ids = [...page.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(new Set(ids).size, ids.length, 'Duplicate DOM IDs detected');
for (const match of script.matchAll(/\$\('([^']+)'\)/g)) {
  assert.ok(ids.includes(match[1]), 'Missing DOM element referenced by script: ' + match[1]);
}
assert.ok(page.includes('Envoyer manuellement'), 'Manual WhatsApp mode missing');
assert.ok(page.includes('Rechercher un destinataire'), 'Generic recipient search missing');
assert.ok(page.includes('Gérer les consentements WhatsApp'), 'Consent management UI missing');
assert.ok(page.includes('Message concernant aussi les parents'), 'Adult student family-message scope missing');
assert.ok(script.includes("fetch(url,{credentials:'same-origin'"), 'Authorized parent search request missing');
assert.ok(script.includes("/api/whatsapp/recipient-search.php?recipient_type="), 'Recipient type search endpoint missing');
assert.ok(script.includes("$('recipient_id').value=recipient.id"), 'Selecting a search result must set the internal recipient UUID');
assert.ok(script.includes("/api/whatsapp/recipient-consents.php"), 'Recipient consent management endpoint missing');
assert.ok(script.includes("/api/whatsapp/send-multi.php"), 'Multi-recipient Meta send endpoint missing');
assert.ok(page.includes('Envoyer automatiquement via Meta'), 'Meta Cloud API mode missing');
assert.ok(script.includes("fetch('/api/whatsapp/manual-preparations.php'"), 'Manual server-side consent/audit endpoint missing');
assert.ok(script.includes("fetch('/api/whatsapp/send.php'"), 'Meta configuration/send endpoint missing');
assert.ok(script.includes("'X-CSRF-Token':csrf"), 'CSRF header missing');
assert.ok(script.includes('idempotency_key:activeSendIdempotencyKey'), 'Stable Meta idempotency key missing');
assert.ok(page.includes('Historique des messages WhatsApp'), 'Message history UI missing');
assert.ok(script.includes('/api/whatsapp/recipient-message-history.php'), 'Message history API missing');
assert.ok(script.includes('whatsapp.message.audit'), 'Message history must be permission-gated');
assert.ok(script.includes('https://wa.me/'), 'Manual click-to-chat navigation missing');
assert.ok(script.includes('Préparation journalisée'), 'Manual preparation must be clearly distinguished from actual send');
assert.ok(script.includes('acceptée(s) par Meta'), 'Provider acceptance must be distinguished from delivery');
assert.ok(!/localStorage|sessionStorage/.test(script), 'Message parameters must not be persisted in browser storage');
assert.ok(page.includes('Le jeton d’accès reste exclusivement dans le fichier protégé'), 'Server-only token warning missing');

const recipientSearchApi = fs.readFileSync('api/whatsapp/recipient-search.php', 'utf8');
assert.ok(recipientSearchApi.includes("requirePermission($pdo, 'whatsapp.recipient.read')"), 'Recipient search must require read permission');
assert.ok(['PARENT', 'STUDENT', 'STAFF', 'TEACHER'].every(type => recipientSearchApi.includes(type)), 'All recipient types must be searchable');
assert.ok(recipientSearchApi.includes('LIMIT 30'), 'Recipient search must cap result count');
const manualApi = fs.readFileSync('api/whatsapp/manual-preparations.php', 'utf8');
assert.ok(manualApi.includes('whatsapp_manual_preparations'), 'Manual preparation audit persistence missing');
assert.ok(manualApi.includes("$consent['status'] !== 'OPTED_IN'"), 'Manual mode must reject inactive consent');
const api = fs.readFileSync('api/whatsapp/send.php', 'utf8');
assert.ok(api.includes("if (!$configured || !in_array($templateName, $allowedTemplates, true))"), 'Unconfigured or unapproved templates must fail closed');
assert.ok(!api.includes("'mode' => 'simulation'"), 'The real-send endpoint must never report a simulated success');
assert.ok(api.includes("'mode' => 'live'"), 'The endpoint must report live mode');
const multiApi = fs.readFileSync('api/whatsapp/send-multi.php', 'utf8');
const resolver = fs.readFileSync('api/whatsapp/recipient-resolver.php', 'utf8');
assert.ok(resolver.includes('student_parents'), 'Student parent links must be resolved server-side');
assert.ok(resolver.includes("America/Port-au-Prince"), 'Majority must be computed server-side at 18 years');
assert.ok(multiApi.includes('whatsapp_recipient_message_log'), 'Each recipient send must be audited independently');
assert.ok(multiApi.includes("$current['status'] !== 'OPTED_IN'"), 'Consent must be rechecked immediately before each send');
const consentApi = fs.readFileSync('api/whatsapp/recipient-consents.php', 'utf8');
assert.ok(consentApi.includes('whatsapp_recipient_consent_audit'), 'Recipient consent changes must be audited');
const webhookApi = fs.readFileSync('api/whatsapp/webhook.php', 'utf8');
assert.ok(webhookApi.includes('hash_hmac'), 'Meta webhook must validate the HMAC signature');
assert.ok(webhookApi.includes('whatsapp_webhook_events'), 'Meta webhook events must be deduplicated and audited');
assert.ok(webhookApi.includes("'DELIVERED'"), 'Meta delivery statuses must be recorded');
const deliveryHelper = fs.readFileSync('api/whatsapp/delivery-status.php', 'utf8');
assert.ok(deliveryHelper.includes('whatsapp_webhook_events'), 'Early Meta receipts must be reconciled after send commit');
console.log('PASS WhatsApp smoke: recipient UI, consent management, multi-recipient Meta, webhook HMAC, history, manual wa.me, CSRF and idempotency');
